"""Build data/processed/*.jsonl, data/splits/MANIFEST.json, results/data_report.md. Idempotent."""
from __future__ import annotations

import argparse
import csv
import json
import statistics as st
import time
from collections import Counter
from pathlib import Path

import numpy as np

from tablehop.data import hybridqa
from tablehop.data.splits import (
    SPLITS,
    assign_splits,
    choose_heldout,
    cluster_tables,
    embed_texts,
    sha256_file,
    table_text,
)
from tablehop.utils.device import get_device


def table_embeddings(raw_dir, tids, cache_path: Path, device: str) -> np.ndarray:
    """Embeddings of table_text for tids (cached by id list hash)."""
    if cache_path.exists():
        z = np.load(cache_path, allow_pickle=True)
        if list(z["ids"]) == list(tids):
            return z["emb"]
    texts = [table_text(hybridqa.load_raw_table(raw_dir, t)) for t in tids]
    emb = embed_texts(texts, device=device, batch_size=128)
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    np.savez(cache_path, ids=np.array(tids), emb=emb)
    return emb


def stats_rows(split: str, exs: list) -> dict:
    n = len(exs)
    q = Counter(e.gold_path_quality for e in exs)
    lens = [len(e.gold_path) for e in exs if e.gold_path]
    at = Counter(e.answer_type for e in exs)
    nr = [len(e.table.rows) for e in exs]
    nc = [len(e.table.header) for e in exs]
    match = 0
    for e in exs:
        if not e.gold_path:
            continue
        last = e.gold_path[-1]
        txt = e.passages.get(last.passage_id, "") if last.kind == "passage" else \
            e.table.rows[last.row][last.col].text
        match += any(a.lower() in txt.lower() for a in e.answer)
    return {
        "split": split, "n": n, "n_tables": len({e.table.id for e in exs}),
        "heuristic": q["heuristic"], "none": q["none"],
        "frac_heuristic": round(q["heuristic"] / max(n, 1), 4),
        "frac_none": round(q["none"] / max(n, 1), 4),
        "path_len_mean": round(st.mean(lens), 3) if lens else 0,
        "path_len_median": st.median(lens) if lens else 0,
        "len1": sum(1 for x in lens if x == 1), "len2": sum(1 for x in lens if x == 2),
        "len3": sum(1 for x in lens if x == 3),
        "ans_type_table": at["table"], "ans_type_passage": at["passage"], "ans_type_none": at["none"],
        "last_entity_contains_answer": round(match / max(len(lens), 1), 4),
        "rows_mean": round(st.mean(nr), 2), "rows_median": st.median(nr),
        "cols_mean": round(st.mean(nc), 2), "cols_median": st.median(nc),
    }


def write_report(stats: list[dict], manifest: dict, path: Path) -> None:
    tot = {k: sum(s[k] for s in stats) for k in ("n", "heuristic", "none")}
    L = ["# Data report (HybridQA splits)", "",
         (f"Generated by scripts/prepare_data.py. Seed {manifest['seed']}, k={manifest['k']}, "
         f"held-out clusters {manifest['heldout_clusters']}. Official HybridQA test is never opened."), "",
         "## Counts and gold-path coverage", "",
         ("| split | questions | tables | heuristic | none | frac heuristic | frac none | "
         "path len mean | last entity contains answer |"), "|---|---|---|---|---|---|---|---|---|"]
    for s in stats:
        L.append(f"| {s['split']} | {s['n']} | {s['n_tables']} | {s['heuristic']} | {s['none']} | "
                 f"{s['frac_heuristic']} | {s['frac_none']} | {s['path_len_mean']} | "
                 f"{s['last_entity_contains_answer']} |")
    L += ["", (f"Overall: {tot['heuristic']}/{tot['n']} heuristic "
          f"({tot['heuristic'] / tot['n']:.3f}), {tot['none']}/{tot['n']} none "
          f"({tot['none'] / tot['n']:.3f}). No path is `clean`: HybridQA has no annotated hop "
          "order, so every path is derived from the weak `answer-node` label plus an anchor "
          "heuristic. `none` = the question has no answer-node. \"Last entity contains answer\" "
          "is the share of heuristic paths whose final cell/passage text contains the gold "
          "answer string (a lower bound on label correctness; answer-node is itself approximate)."),
          "", "## Path length and answer type", "",
          "| split | len1 | len2 | len3 | ans table | ans passage | ans none |", "|---|---|---|---|---|---|---|"]
    for s in stats:
        L.append(f"| {s['split']} | {s['len1']} | {s['len2']} | {s['len3']} | {s['ans_type_table']} | "
                 f"{s['ans_type_passage']} | {s['ans_type_none']} |")
    L += ["", "## Table size", "", "| split | rows mean | rows median | cols mean | cols median |",
          "|---|---|---|---|---|"]
    for s in stats:
        L.append(f"| {s['split']} | {s['rows_mean']} | {s['rows_median']} | {s['cols_mean']} | "
                 f"{s['cols_median']} |")
    L += ["", "## Clusters", "", f"Cluster sizes (train-file tables): {manifest['cluster_sizes']}"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw-dir", default="data/raw/hybridqa")
    ap.add_argument("--out", default="data")
    ap.add_argument("--results", default="results")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--k", type=int, default=20)
    ap.add_argument("--device", default="auto")
    a = ap.parse_args()
    t0 = time.time()
    out, res = Path(a.out), Path(a.results)
    train_q = hybridqa.load_questions(a.raw_dir, "train")
    dev_q = hybridqa.load_questions(a.raw_dir, "dev")
    train_tabs = sorted({q["table_id"] for q in train_q})
    all_tabs = sorted({q["table_id"] for q in train_q} | {q["table_id"] for q in dev_q})
    device = get_device(a.device)
    emb = table_embeddings(a.raw_dir, all_tabs, out / "cache" / "table_emb.npz", device)
    idx = {t: i for i, t in enumerate(all_tabs)}
    train_emb = emb[[idx[t] for t in train_tabs]]
    labels, train_labels = cluster_tables(train_emb, emb, k=a.k, seed=a.seed)
    cluster_of = {t: int(labels[i]) for i, t in enumerate(all_tabs)}
    sizes = {int(c): int((train_labels == c).sum()) for c in range(a.k)}
    heldout = choose_heldout(sizes, len(train_tabs))
    splits = assign_splits(train_q, dev_q, cluster_of, heldout, seed=a.seed)
    src = {"train": "train", "dev": "train", "ood_dev": "train", "test": "dev", "ood_test": "dev"}
    proc = out / "processed"
    proc.mkdir(parents=True, exist_ok=True)
    (out / "splits").mkdir(parents=True, exist_ok=True)
    cache: dict = {}
    stats, files = [], {}
    for s in SPLITS:
        exs = [hybridqa.build_example(a.raw_dir, q, src[s], s, f"c{cluster_of[q['table_id']]}", cache)
               for q in splits[s]]
        p = proc / f"{s}.jsonl"
        with open(p, "w") as f:
            f.writelines(e.to_json() + "\n" for e in exs)
        files[s] = {"n": len(exs), "sha256": sha256_file(p)}
        stats.append(stats_rows(s, exs))
        print(f"{s}: {len(exs)} questions, {stats[-1]['n_tables']} tables")
    manifest = {"seed": a.seed, "k": a.k, "heldout_clusters": heldout, "cluster_sizes": sizes,
                "official_test_used": False, "splits": files}
    (out / "splits" / "MANIFEST.json").write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    write_report(stats, manifest, res / "data_report.md")
    (res / "tables").mkdir(parents=True, exist_ok=True)
    with open(res / "tables" / "data_stats.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(stats[0]))
        w.writeheader()
        w.writerows(stats)
    print(f"done in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
